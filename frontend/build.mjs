#!/usr/bin/env node
/**
 * Build dsadmin stylesheets from @playlovetoys/design-system.
 *
 * One stylesheet per design-system theme. Every stylesheet contains
 * Tailwind 4 + daisyUI 5 (prefix "d-") + the theme tokens + the small
 * dsadmin layer (frontend/src/dsadmin.css). Templates are scanned so only
 * the classes the admin actually uses end up in the output.
 *
 * Usage:
 *   node build.mjs                          # default theme set -> dsadmin/static/dsadmin/css/themes/
 *   node build.mjs --theme workbench        # one theme
 *   node build.mjs --theme brand --out /path/to/project/static/admin-brand.css \
 *        --source /path/to/project/templates  # project build with extra templates scanned
 *
 * Design-system location (first match wins):
 *   $PLT_DESIGN_SYSTEM                      (path to packages/design-system)
 *   node_modules/@playlovetoys/design-system
 *   ../../plt-design-system/packages/design-system
 *   ../../CSS-Style/plt-design-system/packages/design-system
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const DEFAULT_THEMES = ["admin", "nocturne", "workbench", "unconventionals", "playlovetoys"];

function arg(name) {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : undefined;
}
function args(name) {
  const out = [];
  process.argv.forEach((v, i) => {
    if (v === `--${name}` && process.argv[i + 1]) out.push(process.argv[i + 1]);
  });
  return out;
}

function findDesignSystem() {
  const candidates = [
    process.env.PLT_DESIGN_SYSTEM,
    path.join(here, "node_modules", "@playlovetoys", "design-system"),
    path.resolve(repoRoot, "..", "plt-design-system", "packages", "design-system"),
    path.resolve(repoRoot, "..", "aavendano", "plt-design-system", "packages", "design-system"),
    path.resolve(repoRoot, "..", "CSS-Style", "plt-design-system", "packages", "design-system"),
  ].filter(Boolean);
  for (const c of candidates) {
    if (existsSync(path.join(c, "themes")) && existsSync(path.join(c, "src", "daisyui-theme.css"))) {
      return path.resolve(c);
    }
  }
  throw new Error(
    "Cannot find @playlovetoys/design-system. Set PLT_DESIGN_SYSTEM=/path/to/plt-design-system/packages/design-system",
  );
}

const ds = findDesignSystem();
const available = readdirSync(path.join(ds, "themes"))
  .filter((f) => f.endsWith(".css"))
  .map((f) => f.slice(0, -4));

const requested = arg("theme") ? [arg("theme")] : DEFAULT_THEMES;
for (const t of requested) {
  if (!available.includes(t)) {
    throw new Error(`Unknown theme "${t}". Available: ${available.sort().join(", ")}`);
  }
}

const outArg = arg("out");
if (outArg && requested.length !== 1) throw new Error("--out requires --theme");
const extraSources = args("source").map((s) => path.resolve(s));
const minify = !process.argv.includes("--no-minify");

const buildDir = path.join(here, ".build");
mkdirSync(buildDir, { recursive: true });
const tailwind = path.join(here, "node_modules", ".bin", "tailwindcss");
if (!existsSync(tailwind)) throw new Error("Run `npm install` in frontend/ first.");

const rel = (p) => path.relative(buildDir, p).split(path.sep).join("/");

for (const theme of requested) {
  const sources = [
    path.join(repoRoot, "dsadmin", "templates"),
    path.join(repoRoot, "dsadmin", "static", "dsadmin", "js"),
    path.join(repoRoot, "dsadmin"), // python helpers emit d-* classes (widgets, display)
    ...extraSources,
  ];
  const entry = [
    `/* generated by frontend/build.mjs — theme: ${theme} */`,
    `@import "tailwindcss" source(none);`,
    ...sources.map((s) => `@source "${rel(s)}";`),
    `@source not "${rel(path.join(repoRoot, "dsadmin", "static", "dsadmin", "css"))}";`,
    `@import "${rel(path.join(ds, "themes", `${theme}.css`))}";`,
    `@import "${rel(path.join(here, "src", "dsadmin.css"))}";`,
    ...(existsSync(path.join(here, "src", "theme-fixes", `${theme}.css`))
      ? [`@import "${rel(path.join(here, "src", "theme-fixes", `${theme}.css`))}";`]
      : []),
    "",
  ].join("\n");
  const entryFile = path.join(buildDir, `${theme}.css`);
  writeFileSync(entryFile, entry);
  const out =
    outArg ? path.resolve(outArg) : path.join(repoRoot, "dsadmin", "static", "dsadmin", "css", "themes", `${theme}.css`);
  mkdirSync(path.dirname(out), { recursive: true });
  const res = spawnSync(tailwind, ["-i", entryFile, "-o", out, ...(minify ? ["--minify"] : [])], {
    cwd: here,
    stdio: "inherit",
    env: { ...process.env, NODE_PATH: path.join(here, "node_modules") },
  });
  if (res.status !== 0) process.exit(res.status ?? 1);
  process.stdout.write(`built ${theme} -> ${path.relative(process.cwd(), out)}\n`);
}
if (!process.argv.includes("--keep")) rmSync(buildDir, { recursive: true, force: true });
